"""Deterministic, atomic JSON helpers for the asset pipeline.

The Blender stages run from arbitrary working directories and write several
manifests consumed by the Unreal importer.  Use :func:`write_json` so a crash
during serialization cannot leave a half-written manifest, and so Windows
newline translation never changes the generated bytes.
"""

from __future__ import annotations

import json
import os
import tempfile
from pathlib import Path
from typing import Any


def read_json(path: str | os.PathLike[str]) -> Any:
    with Path(path).open("r", encoding="utf-8") as handle:
        return json.load(handle)


def write_json(
    path: str | os.PathLike[str],
    value: Any,
    *,
    indent: int | None = None,
    separators: tuple[str, str] | None = None,
    ensure_ascii: bool = True,
    sort_keys: bool = False,
    trailing_newline: bool = False,
) -> None:
    """Serialize ``value`` to ``path`` atomically (UTF-8, LF line endings)."""
    target = Path(path)
    target.parent.mkdir(parents=True, exist_ok=True)
    payload = json.dumps(
        value,
        indent=indent,
        separators=separators,
        ensure_ascii=ensure_ascii,
        sort_keys=sort_keys,
    )
    if trailing_newline:
        payload += "\n"
    fd, temp_name = tempfile.mkstemp(prefix=target.name + ".", suffix=".tmp", dir=str(target.parent))
    temp_path = Path(temp_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(payload)
        os.replace(temp_path, target)
    finally:
        if temp_path.exists():
            try:
                temp_path.unlink()
            except OSError:
                pass
