#!/usr/bin/env python3
"""Write Docs/Effects/COVERAGE.md from the current data.

The report is deterministic: rerunning the tool on the same data produces the
same file. It reads the manifest, fusions.json, rituals.json and decks.json and
does not modify any runtime data.

Usage:
    python Tools/effects/report_coverage.py
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import effect_data as data

RISK_KEYWORDS = [    ("negate", 5),
    ("control", 5),
    ("copy", 5),
    ("banish", 4),
    ("remove from play", 4),
    ("destroy all", 4),
    ("chain", 4),
    ("random", 3),
    ("coin", 3),
    ("die", 3),
    ("dice", 3),
    ("once per turn", 2),
    ("for the rest of", 3),
    ("until", 2),
    ("except", 3),
    ("each", 2),
    ("reveal", 2),
    ("shuffle", 2),
    ("discard", 2),
    ("tribute", 2),
    ("summon", 2),
    ("target", 1),
    ("damage", 1),
    ("life points", 1),
    ("zone", 2),
]

LANE_TITLES = {
    "story_event_decks": "Story event opponent decks",
    "opponent_decks": "Opponent decks (full roster)",
    "puzzle_decks": "Puzzle decks",
    "starter_decks": "Starter / player decks",
    "shop_packs": "Shop packs",
    "story_rewards": "Story reward grants",
    "long_tail": "Long tail",
}


def _table(headers: list[str], rows: list[list[object]]) -> list[str]:
    lines = ["| " + " | ".join(headers) + " |"]
    lines.append("| " + " | ".join("---" for _ in headers) + " |")
    for row in rows:
        lines.append("| " + " | ".join(str(value) for value in row) + " |")
    return lines


def _status_of(entry: dict) -> str:
    return entry["status"]


def _risk(entry: dict, card: dict) -> tuple[int, list[str]]:
    text = (card.get("description") or "").lower()
    score = 0
    tags: list[str] = []
    if entry["status"] == "pending":
        score += 40
        tags.append("pending")
    elif entry["status"] == "unsupported":
        score += 60
        tags.append("unsupported")
    if entry["tier"] == 0:
        score += 30
        tags.append("tier0")
    elif entry["tier"] == 1:
        score += 18
        tags.append("tier1")
    elif entry["tier"] == 2:
        score += 12
        tags.append("tier2")
    score += min(20, len(text) // 90)
    if len(text) >= 240:
        tags.append("long-text")
    for keyword, points in RISK_KEYWORDS:
        if keyword in text:
            score += points
            if keyword in {"negate", "control", "copy", "banish", "chain", "coin", "die", "dice", "random"}:
                tags.append(keyword.replace(" ", "-"))
    card_type = card.get("card_type", "")
    if card_type == "Trap":
        score += 5
        tags.append("trap")
    elif card_type == "Spell":
        score += 2
    elif card_type == "Effect Monster":
        score += 1
    if entry["status"] == "scripted":
        score -= 55
    if entry["implementation"] == "engine_cpp":
        score -= 10
    if entry["tier"] == 3:
        tags.append("tier3")
    return score, tags


def build_report() -> str:
    cards = data.load_cards()
    by_id = data.cards_by_id(cards)
    manifest = data.load_json(data.MANIFEST_PATH)
    entries = manifest["cards"]
    index = {entry["id"]: entry for entry in entries}
    decks = data.load_decks()
    deck_membership: dict[int, list[str]] = {}
    for deck in decks:
        deck_name = deck.get("name") or deck.get("id", "?")
        for card_id in deck.get("cards", []) + deck.get("extra", []):
            deck_membership.setdefault(int(card_id), [])
            if deck_name not in deck_membership[int(card_id)]:
                deck_membership[int(card_id)].append(deck_name)

    lines: list[str] = []
    lines.append("# Card effect coverage")
    lines.append("")
    lines.append(
        "Generated by `python Tools/effects/report_coverage.py`. The manifest is the "
        "source of truth: one row per card in `cards.json`."
    )
    lines.append("")
    lines.append("## Status model")
    lines.append("")
    lines.append("| Status | Meaning |")
    lines.append("| --- | --- |")
    lines.append(
        "| `scripted` | A data script exists (`Effects/scripts/<id>.json`), or the card is part of the 137-card regression baseline and has a verified name handler in `DADuelEngine.cpp`. |"
    )
    lines.append(
        "| `vanilla` | No standalone effect to script. Normal Monsters use generic rules; effect-free Fusions/Rituals use `fusions.json` / `rituals.json`; specific Ritual Spell procedures are owned by `rituals.json`; summoning-restriction-only monsters have no executable effect. |"
    )
    lines.append(
        "| `pending` | Effect text exists, but the whole printed effect is not covered by a validated data script or verified engine handler. `pending_reason_code` names the blocking runtime capability. |"
    )
    lines.append(
        "| `unsupported` | The card cannot be represented yet. This is always an explicit release blocker. |"
    )
    lines.append("")

    summary = manifest["summary"]
    lines.append("## Headline counts")
    lines.append("")
    lines.append(f"- Cards: **{summary['total']}**")
    lines.append(f"- Data scripts: **{len(data.script_files())}**")
    lines.append(
        "- Status: "
        + ", ".join(
            f"`{status}`={summary['by_status'][status]}" for status in data.STATUS_ORDER
        )
    )
    lines.append(
        "- Tier: "
        + ", ".join(
            f"T{ tier }={summary['by_tier'][str(tier)]}" for tier in (0, 1, 2, 3)
        )
    )
    tier0 = [entry for entry in entries if entry["tier"] == 0]
    tier0_bad = [entry for entry in tier0 if entry["status"] not in ("scripted", "vanilla")]
    lines.append(
        f"- Tier 0 regression baseline: **{len(tier0)} cards**, "
        f"**{len(tier0) - len(tier0_bad)}/{len(tier0)} covered**, "
        f"{len(tier0_bad)} pending/unsupported."
    )
    lines.append("")

    script_count = len(data.script_files())
    hand_written = len([card_id for card_id in data.tier1_ids() if (data.SCRIPTS_DIR / f"{card_id}.json").exists()])
    lines.append("## Method")
    lines.append("")
    lines.append(
        f"- **{script_count} validated card scripts** exist: {hand_written} hand-authored "
        f"examples and {script_count - hand_written} generated by `Tools/effects/generate_scripts.py`."
    )
    lines.append(
        "- The generator uses whole-card patterns from `Tools/effects/effect_patterns.py`. A card is "
        "scripted only when every printed clause is represented; otherwise it stays `pending` with a "
        "reason code."
    )
    lines.append(
        "- `python Tools/effects/validate_effects.py` checks the JSON Schema, per-card source text, "
        "manifest hashes, script ids, fusion/ritual accounting and usage legality."
    )
    lines.append("")

    lane_path = data.EFFECTS_DIR / "coverage_by_deck.json"
    lines.append("## Gate 3.1 batch record")
    lines.append("")
    lines.append(
        "| Metric | Before batch | After batch |"
    )
    lines.append("| --- | ---: | ---: |")
    lines.append(f"| Data scripts | 155 | {script_count} |")
    lines.append(f"| `scripted` | 264 | {summary['by_status']['scripted']} |")
    lines.append(f"| `vanilla` | 345 | {summary['by_status']['vanilla']} |")
    lines.append(f"| `pending` | 591 | {summary['by_status']['pending']} |")
    lines.append("| `unsupported` | 0 | 0 |")
    lines.append("")
    lane_story_pending = None
    if lane_path.exists():
        lane_story_pending = data.load_json(lane_path).get("summary", {}).get(
            "categories", {}
        ).get("story_event_decks", {}).get("pending")
    lines.append(
        "The previous story backlog was **92 pending cards from a 213-card story deck union**. "
        f"Incoming deck data expanded that lane to **368 unique cards**; it now has "
        f"**{lane_story_pending if lane_story_pending is not None else '?'} pending**, "
        "so the lane totals are not like-for-like. Of the original 92 cards, **38 are now "
        "`scripted` and 54 remain pending**. The current story lane's pending cards are listed "
        "with their reasons in `COVERAGE_BY_DECK.md`; overall remaining work is grouped by reason "
        "below."
    )
    lines.append("")
    lines.append("## Runtime caveats in this batch")
    lines.append("")
    lines.append(
        "- **Generic Equip/Field activation persistence.** The 40 `equip_continuous` / "
        "`field_continuous` scripts are schema-valid, but `FDuelEngine::ActivateSpell` still "
        "decides whether a card stays on the field with the legacy `IsEquipName` / "
        "`IsFieldSpellName` lists. Until A04 generalises `bStays`, these cards only apply when "
        "the card is already placed/attached; activating them from the hand sends them to the "
        "Graveyard after resolution."
    )
    lines.append(
        "- **Self-trigger source binding.** Field-scanned triggers such as `on_battle_destroy`, "
        "`on_sent_to_graveyard`, `on_tribute_summon`, `on_position_change` and `on_summon` still "
        "consider other card ids on the field. The new attacker hooks use the supported "
        "`battle_involving_self` predicate where possible, but A04 still needs strict "
        "self-trigger binding (or an `event_source_is_self` condition) for the remaining cases."
    )
    lines.append("")

    if lane_path.exists():
        lane_report = data.load_json(lane_path)
        lane_summary = lane_report.get("summary", {})
        lines.append("## Coverage by content lane")
        lines.append("")
        lines.append(
            "Generated by `python Tools/effects/coverage.py` (JSON: "
            "`Content/Data/Effects/coverage_by_deck.json`, detail: "
            "`Docs/Effects/COVERAGE_BY_DECK.md`). A card can belong to more than one "
            "lane; `pending_by_priority` assigns it to the first reachable lane."
        )
        lines.append("")
        lane_rows: list[list[object]] = []
        for name in lane_report.get("source", {}).get("priority_order", []):
            category = lane_summary.get("categories", {}).get(name, {})
            lane_rows.append(
                [
                    LANE_TITLES.get(name, name),
                    category.get("cards", 0),
                    category.get("pending", 0),
                    category.get("covered", 0),
                ]
            )
        lines.extend(_table(["Lane", "Unique cards", "Pending", "Covered"], lane_rows))
        lines.append("")
        priority = lane_summary.get("pending_by_priority", {})
        if priority:
            lines.append(
                "Pending by priority: "
                + ", ".join(
                    f"`{LANE_TITLES.get(name, name)}`={count}"
                    for name, count in priority.items()
                    if count
                )
                + "."
            )
            lines.append("")

    pending_reasons: dict[str, int] = {}
    for entry in entries:
        if entry.get("status") != "pending":
            continue
        code = entry.get("pending_reason_code", "unclassified")
        pending_reasons[code] = pending_reasons.get(code, 0) + 1
    if pending_reasons:
        lines.append("## Pending by reason")
        lines.append("")
        reason_rows = [
            [f"`{code}`", count]
            for code, count in sorted(pending_reasons.items(), key=lambda item: (-item[1], item[0]))
        ]
        lines.extend(_table(["Reason code", "Pending"], reason_rows))
        lines.append("")

    if lane_path.exists():
        lane_report = data.load_json(lane_path)
        story_items = lane_report.get("categories", {}).get("story_event_decks", {}).get("items", [])
        roster_items = lane_report.get("categories", {}).get("opponent_decks", {}).get("items", [])

        def deck_count(items: list[dict], card_id: int) -> int:
            return sum(1 for item in items if card_id in item.get("pending_ids", []))

        pending_scored = []
        for entry in entries:
            if entry.get("status") != "pending":
                continue
            card_id = int(entry["id"])
            pending_scored.append(
                (
                    deck_count(story_items, card_id),
                    deck_count(roster_items, card_id),
                    int(entry["tier"]),
                    entry,
                )
            )
        pending_scored.sort(key=lambda item: (-item[0], -item[1], item[2], item[3]["id"]))
        lines.append("## Top used-but-pending cards")
        lines.append("")
        lines.append(
            "`Story decks` counts the event opponent decks that contain the card; "
            "`Roster decks` counts all opponent deck files. This is an ordering aid, not a "
            "claim that every copy is played in every listed deck."
        )
        lines.append("")
        top_rows = []
        for story_count, roster_count, _tier, entry in pending_scored[:25]:
            top_rows.append(
                [
                    entry["id"],
                    entry["name"],
                    entry["type"],
                    story_count,
                    roster_count,
                    f"`{entry.get('pending_reason_code', 'unclassified')}`",
                ]
            )
        lines.extend(
            _table(
                ["ID", "Name", "Type", "Story decks", "Roster decks", "Reason"],
                top_rows,
            )
        )
        lines.append("")

    lines.append("## Status by card type")
    lines.append("")
    type_rows: list[list[object]] = []
    for card_type in data.CARD_TYPE_ORDER:
        counts = {
            status: sum(
                1
                for entry in entries
                if entry["type"] == card_type and entry["status"] == status
            )
            for status in data.STATUS_ORDER
        }
        total = sum(counts.values())
        type_rows.append(
            [card_type, total]
            + [counts[status] for status in data.STATUS_ORDER]
        )
    lines.extend(
        _table(
            ["Card type", "Total"] + data.STATUS_ORDER,
            type_rows,
        )
    )
    lines.append("")

    lines.append("## Status by tier")
    lines.append("")
    tier_rows: list[list[object]] = []
    for tier in (0, 1, 2, 3):
        counts = {
            status: sum(
                1
                for entry in entries
                if entry["tier"] == tier and entry["status"] == status
            )
            for status in data.STATUS_ORDER
        }
        tier_rows.append(
            [f"Tier {tier}", sum(counts.values())]
            + [counts[status] for status in data.STATUS_ORDER]
        )
    lines.extend(
        _table(
            ["Tier", "Total"] + data.STATUS_ORDER,
            tier_rows,
        )
    )
    lines.append("")

    lines.append("## How Tier 0 was identified")
    lines.append("")
    lines.append(
        "The current four decks in `Content/Data/decks.json` contain exactly **137 unique "
        "cards**. That union is the regression baseline and is assigned Tier 0. Of those "
        "137, **110 names occur verbatim in `DADuelEngine.cpp`** (109 effect-bearing cards "
        "plus Harpie Lady, which is a Normal Monster); the other **27** are Normal Monsters "
        "or the effect-free Fusion Monster 319, handled by generic rules and "
        "`fusions.json`. The manifest therefore credits 109 `engine_cpp` scripts and 28 "
        "`vanilla` cards, with zero pending Tier 0 cards."
    )
    lines.append("")
    lines.append(
        "This is an attestation of the current C++ baseline, not a claim that those 109 "
        "cards already have data scripts. When A04 ports the handlers into the effect "
        "runtime, each one must move from `implementation=engine_cpp` to "
        "`implementation=data_script` without changing behaviour."
    )
    lines.append("")

    lines.append("## Tier 0 cards and current status")
    lines.append("")
    tier0_rows: list[list[object]] = []
    for entry in sorted(tier0, key=lambda item: item["id"]):
        tier0_rows.append(
            [
                entry["id"],
                entry["name"],
                entry["type"],
                entry["status"],
                entry["implementation"],
                ", ".join(deck_membership.get(entry["id"], [])),
            ]
        )
    lines.extend(
        _table(
            ["ID", "Name", "Type", "Status", "Implementation", "Decks"],
            tier0_rows,
        )
    )
    lines.append("")

    lines.append("## Top 50 highest-risk cards")
    lines.append("")
    lines.append(
        "Risk is a prioritisation score, not a rules judgement. It combines pending "
        "status, tier, effect-text length and keywords that historically hide timing, "
        "targeting and chain bugs (negate, control, copy, banish, random, once-per-turn)."
    )
    lines.append("")
    scored = []
    for entry in entries:
        card = by_id[entry["id"]]
        score, tags = _risk(entry, card)
        scored.append((score, entry, tags))
    scored.sort(key=lambda item: (-item[0], item[1]["id"]))
    risk_rows: list[list[object]] = []
    for score, entry, tags in scored[:50]:
        risk_rows.append(
            [
                score,
                entry["id"],
                entry["name"],
                entry["type"],
                f"T{entry['tier']}",
                entry["status"],
                ", ".join(dict.fromkeys(tags)) or "-",
            ]
        )
    lines.extend(
        _table(
            ["Risk", "ID", "Name", "Type", "Tier", "Status", "Signals"],
            risk_rows,
        )
    )
    lines.append("")

    lines.append("## Fusion coverage")
    lines.append("")
    try:
        fusions = data.load_json(data.FUSIONS_PATH)
    except Exception:
        fusions = []
    if isinstance(fusions, list):
        resolved = [item for item in fusions if item.get("status") == "resolved"]
        unresolved = [item for item in fusions if item.get("status") != "resolved"]
        engine_ready = [item for item in fusions if item.get("engineReady")]
        lines.append(
            f"- Fusion Monsters: **{len(fusions)}**; resolved recipes: **{len(resolved)}**; "
            f"explicit unresolved: **{len(unresolved)}**; engine-ready recipes: **{len(engine_ready)}**."
        )
        confidence_counts = {
            key: sum(1 for item in fusions if item.get("confidence") == key)
            for key in ("high", "medium", "low", "unresolved")
        }
        lines.append(
            "- Confidence: "
            + ", ".join(f"`{key}`={value}" for key, value in confidence_counts.items())
        )
        fusion_type_counts: dict[str, int] = {}
        for item in fusions:
            for fusion_type in item.get("fusionTypes", []):
                fusion_type_counts[fusion_type] = fusion_type_counts.get(fusion_type, 0) + 1
        lines.append(
            "- Fusion types: "
            + ", ".join(
                f"`{key}`={value}" for key, value in sorted(fusion_type_counts.items())
            )
        )
        if unresolved:
            lines.append("")
            lines.append("Unresolved Fusion monsters:")
            for item in unresolved:
                lines.append(
                    f"- **{item['result']} {item['name']}** — {item.get('reason', 'no reason recorded')}"
                )
        contact = [item for item in fusions if "Contact Fusion" in item.get("fusionTypes", [])]
        if contact:
            lines.append("")
            lines.append(
                "Contact Fusion recipes (data-complete, runtime primitive missing): "
                + ", ".join(f"{item['result']} {item['name']}" for item in contact)
                + "."
            )
        unavailable = [
            item
            for item in resolved
            if not item.get("engineReady") and "Contact Fusion" not in item.get("fusionTypes", [])
        ]
        if unavailable:
            lines.append("")
            lines.append(
                "Other resolved but not-yet-engine-ready recipes: "
                + ", ".join(f"{item['result']} {item['name']}" for item in unavailable)
                + "."
            )
    lines.append("")

    lines.append("## Ritual coverage")
    lines.append("")
    try:
        rituals = data.load_json(data.RITUALS_PATH)
    except Exception:
        rituals = []
    if isinstance(rituals, list):
        resolved = [item for item in rituals if item.get("status") == "resolved"]
        lines.append(
            f"- Ritual Monsters: **{len(rituals)}**; resolved procedures: **{len(resolved)}**; "
            f"unresolved: **{len(rituals) - len(resolved)}**."
        )
        confidence_counts = {
            key: sum(1 for item in rituals if item.get("confidence") == key)
            for key in ("high", "medium", "low", "unresolved")
        }
        lines.append(
            "- Confidence: "
            + ", ".join(f"`{key}`={value}" for key, value in confidence_counts.items())
        )
        for item in rituals:
            if item.get("confidence") == "medium":
                note = "; ".join(item.get("notes", []))
                lines.append(f"- **{item['monster']} {item['name']}** — {note}")
    lines.append("")

    lines.append("## Next batch")
    lines.append("")
    lines.append(
        "1. Fix the highest-leverage runtime gaps named above: `runtime_special_summon_position` "
        "(Monster Reborn), `runtime_attack_lock` (Threatening Roar / Messenger of Peace), "
        "`runtime_standby_side` (Imperial Order / Fairy Box), `runtime_inherent_special_summon` "
        "(Cyber Dragon), and `runtime_dynamic_stat` (Dark Magician Girl / Machine King)."
    )
    lines.append(
        "2. Add whole-card templates for any remaining single-clause cards in the story lane. "
        "Do not script a card with a second unsupported clause."
    )
    lines.append(
        "3. After the story lane, process roster-only cards, then the shop long tail. "
        "The generated JSON has the complete list and labels."
    )
    lines.append("")

    lines.append("## Runtime and content blockers")
    lines.append("")
    pending_count = summary["by_status"].get("pending", 0)
    lines.append(
        f"1. **{pending_count} pending effect cards** remain. They are honest `pending` rows with a "
        "`pending_reason_code`, not silent omissions. The full list by reachability is in "
        "`Docs/Effects/COVERAGE_BY_DECK.md`."
    )
    tier2_count = summary["by_tier"].get("2", 0)
    tier2_entries = [entry for entry in entries if entry["tier"] == 2]
    tier2_pending = sum(1 for entry in tier2_entries if entry["status"] == "pending")
    lines.append(
        f"2. **Tier 2 contains {tier2_count} cards** because A06/A07 usage datasets (Shop/packs.json, Opponents, Puzzles, Decks, Exams) now reference most of the pool. "
        f"{tier2_count - tier2_pending} are covered and **{tier2_pending} are pending**. "
        "`audit.py` treats Tier 2 as informational in the baseline stage and as a hard gate with `--release`."
    )
    if pending_reasons:
        top_reasons = sorted(pending_reasons.items(), key=lambda item: (-item[1], item[0]))[:8]
        lines.append(
            "3. **Remaining pending work clusters around runtime gaps:** "
            + ", ".join(f"`{code}`={count}" for code, count in top_reasons)
            + ". Scripts are only emitted when the whole printed effect is covered; partial "
            "effects stay pending rather than being approximated."
        )
    lines.append(
        f"4. **Fusion 1156 UFOroid Fighter** is unresolved: its text mixes one named material with a generic `1 Warrior-Type monster` slot, which the current recipe model cannot express."
    )
    lines.append(
        "5. **Contact Fusion** (745, 747, 774, 775) and **Power Bond / Fusion Gate** are data-valid but not resolved by the current engine. A04 needs the primitives listed in `RUNTIME_INTERFACE.md`."
    )
    lines.append(
        "6. **Ritual procedures** are complete as data (22/22), but the engine currently resolves only Legendary Flame Lord. A04 must load `rituals.json` and support generic Ritual Summons."
    )
    lines.append(
        "7. Tier 0 is green only because the C++ name handlers still exist. The 109 `engine_cpp` rows are the regression contract for A04's refactor."
    )
    lines.append("")

    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Build the report in memory without writing it.",
    )
    args = parser.parse_args(argv)
    report = build_report()
    if not args.check:
        output = data.ROOT / "Docs" / "Effects" / "COVERAGE.md"
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(report, encoding="utf-8", newline="\n")
        print(f"Wrote {output.relative_to(data.ROOT)}")
    else:
        print(report)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
