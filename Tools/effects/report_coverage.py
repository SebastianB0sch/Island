#!/usr/bin/env python3
"""Write Docs/Effects/COVERAGE.md from the current data.

The report is deterministic: rerunning the tool on the same data produces the
same file. It reads the manifest, fusions.json, rituals.json and decks.json and
does not modify any runtime data.

Usage:
    python Tools/effects/report_coverage.py
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import effect_data as data

RISK_KEYWORDS = [
    ("negate", 5),
    ("control", 5),
    ("copy", 5),
    ("banish", 4),
    ("remove from play", 4),
    ("destroy all", 4),
    ("chain", 4),
    ("random", 3),
    ("coin", 3),
    ("die", 3),
    ("dice", 3),
    ("once per turn", 2),
    ("for the rest of", 3),
    ("until", 2),
    ("except", 3),
    ("each", 2),
    ("reveal", 2),
    ("shuffle", 2),
    ("discard", 2),
    ("tribute", 2),
    ("summon", 2),
    ("target", 1),
    ("damage", 1),
    ("life points", 1),
    ("zone", 2),
]


def _table(headers: list[str], rows: list[list[object]]) -> list[str]:
    lines = ["| " + " | ".join(headers) + " |"]
    lines.append("| " + " | ".join("---" for _ in headers) + " |")
    for row in rows:
        lines.append("| " + " | ".join(str(value) for value in row) + " |")
    return lines


def _status_of(entry: dict) -> str:
    return entry["status"]


def _risk(entry: dict, card: dict) -> tuple[int, list[str]]:
    text = (card.get("description") or "").lower()
    score = 0
    tags: list[str] = []
    if entry["status"] == "pending":
        score += 40
        tags.append("pending")
    elif entry["status"] == "unsupported":
        score += 60
        tags.append("unsupported")
    if entry["tier"] == 0:
        score += 30
        tags.append("tier0")
    elif entry["tier"] == 1:
        score += 18
        tags.append("tier1")
    elif entry["tier"] == 2:
        score += 12
        tags.append("tier2")
    score += min(20, len(text) // 90)
    if len(text) >= 240:
        tags.append("long-text")
    for keyword, points in RISK_KEYWORDS:
        if keyword in text:
            score += points
            if keyword in {"negate", "control", "copy", "banish", "chain", "coin", "die", "dice", "random"}:
                tags.append(keyword.replace(" ", "-"))
    card_type = card.get("card_type", "")
    if card_type == "Trap":
        score += 5
        tags.append("trap")
    elif card_type == "Spell":
        score += 2
    elif card_type == "Effect Monster":
        score += 1
    if entry["status"] == "scripted":
        score -= 55
    if entry["implementation"] == "engine_cpp":
        score -= 10
    if entry["tier"] == 3:
        tags.append("tier3")
    return score, tags


def build_report() -> str:
    cards = data.load_cards()
    by_id = data.cards_by_id(cards)
    manifest = data.load_json(data.MANIFEST_PATH)
    entries = manifest["cards"]
    index = {entry["id"]: entry for entry in entries}
    decks = data.load_decks()
    deck_membership: dict[int, list[str]] = {}
    for deck in decks:
        deck_name = deck.get("name") or deck.get("id", "?")
        for card_id in deck.get("cards", []) + deck.get("extra", []):
            deck_membership.setdefault(int(card_id), [])
            if deck_name not in deck_membership[int(card_id)]:
                deck_membership[int(card_id)].append(deck_name)

    lines: list[str] = []
    lines.append("# Card effect coverage")
    lines.append("")
    lines.append(
        "Generated by `python Tools/effects/report_coverage.py`. The manifest is the "
        "source of truth: one row per card in `cards.json`."
    )
    lines.append("")
    lines.append("## Status model")
    lines.append("")
    lines.append("| Status | Meaning |")
    lines.append("| --- | --- |")
    lines.append(
        "| `scripted` | A data script exists (`Effects/scripts/<id>.json`), or the card is part of the 137-card regression baseline and has a verified name handler in `DADuelEngine.cpp`. |"
    )
    lines.append(
        "| `vanilla` | No effect text. Normal Monsters use generic rules; effect-free Fusions/Rituals use `fusions.json` / `rituals.json`. |"
    )
    lines.append(
        "| `pending` | Effect text exists, but there is no data script or verified engine handler yet. |"
    )
    lines.append(
        "| `unsupported` | The card cannot be represented yet. This is always an explicit release blocker. |"
    )
    lines.append("")

    summary = manifest["summary"]
    lines.append("## Headline counts")
    lines.append("")
    lines.append(f"- Cards: **{summary['total']}**")
    lines.append(f"- Data scripts: **{len(data.script_files())}**")
    lines.append(
        "- Status: "
        + ", ".join(
            f"`{status}`={summary['by_status'][status]}" for status in data.STATUS_ORDER
        )
    )
    lines.append(
        "- Tier: "
        + ", ".join(
            f"T{ tier }={summary['by_tier'][str(tier)]}" for tier in (0, 1, 2, 3)
        )
    )
    tier0 = [entry for entry in entries if entry["tier"] == 0]
    tier0_bad = [entry for entry in tier0 if entry["status"] not in ("scripted", "vanilla")]
    lines.append(
        f"- Tier 0 regression baseline: **{len(tier0)} cards**, "
        f"**{len(tier0) - len(tier0_bad)}/{len(tier0)} covered**, "
        f"{len(tier0_bad)} pending/unsupported."
    )
    lines.append("")

    lines.append("## Status by card type")
    lines.append("")
    type_rows: list[list[object]] = []
    for card_type in data.CARD_TYPE_ORDER:
        counts = {
            status: sum(
                1
                for entry in entries
                if entry["type"] == card_type and entry["status"] == status
            )
            for status in data.STATUS_ORDER
        }
        total = sum(counts.values())
        type_rows.append(
            [card_type, total]
            + [counts[status] for status in data.STATUS_ORDER]
        )
    lines.extend(
        _table(
            ["Card type", "Total"] + data.STATUS_ORDER,
            type_rows,
        )
    )
    lines.append("")

    lines.append("## Status by tier")
    lines.append("")
    tier_rows: list[list[object]] = []
    for tier in (0, 1, 2, 3):
        counts = {
            status: sum(
                1
                for entry in entries
                if entry["tier"] == tier and entry["status"] == status
            )
            for status in data.STATUS_ORDER
        }
        tier_rows.append(
            [f"Tier {tier}", sum(counts.values())]
            + [counts[status] for status in data.STATUS_ORDER]
        )
    lines.extend(
        _table(
            ["Tier", "Total"] + data.STATUS_ORDER,
            tier_rows,
        )
    )
    lines.append("")

    lines.append("## How Tier 0 was identified")
    lines.append("")
    lines.append(
        "The current four decks in `Content/Data/decks.json` contain exactly **137 unique "
        "cards**. That union is the regression baseline and is assigned Tier 0. Of those "
        "137, **110 names occur verbatim in `DADuelEngine.cpp`** (109 effect-bearing cards "
        "plus Harpie Lady, which is a Normal Monster); the other **27** are Normal Monsters "
        "or the effect-free Fusion Monster 319, handled by generic rules and "
        "`fusions.json`. The manifest therefore credits 109 `engine_cpp` scripts and 28 "
        "`vanilla` cards, with zero pending Tier 0 cards."
    )
    lines.append("")
    lines.append(
        "This is an attestation of the current C++ baseline, not a claim that those 109 "
        "cards already have data scripts. When A04 ports the handlers into the effect "
        "runtime, each one must move from `implementation=engine_cpp` to "
        "`implementation=data_script` without changing behaviour."
    )
    lines.append("")

    lines.append("## Tier 0 cards and current status")
    lines.append("")
    tier0_rows: list[list[object]] = []
    for entry in sorted(tier0, key=lambda item: item["id"]):
        tier0_rows.append(
            [
                entry["id"],
                entry["name"],
                entry["type"],
                entry["status"],
                entry["implementation"],
                ", ".join(deck_membership.get(entry["id"], [])),
            ]
        )
    lines.extend(
        _table(
            ["ID", "Name", "Type", "Status", "Implementation", "Decks"],
            tier0_rows,
        )
    )
    lines.append("")

    lines.append("## Top 50 highest-risk cards")
    lines.append("")
    lines.append(
        "Risk is a prioritisation score, not a rules judgement. It combines pending "
        "status, tier, effect-text length and keywords that historically hide timing, "
        "targeting and chain bugs (negate, control, copy, banish, random, once-per-turn)."
    )
    lines.append("")
    scored = []
    for entry in entries:
        card = by_id[entry["id"]]
        score, tags = _risk(entry, card)
        scored.append((score, entry, tags))
    scored.sort(key=lambda item: (-item[0], item[1]["id"]))
    risk_rows: list[list[object]] = []
    for score, entry, tags in scored[:50]:
        risk_rows.append(
            [
                score,
                entry["id"],
                entry["name"],
                entry["type"],
                f"T{entry['tier']}",
                entry["status"],
                ", ".join(dict.fromkeys(tags)) or "-",
            ]
        )
    lines.extend(
        _table(
            ["Risk", "ID", "Name", "Type", "Tier", "Status", "Signals"],
            risk_rows,
        )
    )
    lines.append("")

    lines.append("## Fusion coverage")
    lines.append("")
    try:
        fusions = data.load_json(data.FUSIONS_PATH)
    except Exception:
        fusions = []
    if isinstance(fusions, list):
        resolved = [item for item in fusions if item.get("status") == "resolved"]
        unresolved = [item for item in fusions if item.get("status") != "resolved"]
        engine_ready = [item for item in fusions if item.get("engineReady")]
        lines.append(
            f"- Fusion Monsters: **{len(fusions)}**; resolved recipes: **{len(resolved)}**; "
            f"explicit unresolved: **{len(unresolved)}**; engine-ready recipes: **{len(engine_ready)}**."
        )
        confidence_counts = {
            key: sum(1 for item in fusions if item.get("confidence") == key)
            for key in ("high", "medium", "low", "unresolved")
        }
        lines.append(
            "- Confidence: "
            + ", ".join(f"`{key}`={value}" for key, value in confidence_counts.items())
        )
        fusion_type_counts: dict[str, int] = {}
        for item in fusions:
            for fusion_type in item.get("fusionTypes", []):
                fusion_type_counts[fusion_type] = fusion_type_counts.get(fusion_type, 0) + 1
        lines.append(
            "- Fusion types: "
            + ", ".join(
                f"`{key}`={value}" for key, value in sorted(fusion_type_counts.items())
            )
        )
        if unresolved:
            lines.append("")
            lines.append("Unresolved Fusion monsters:")
            for item in unresolved:
                lines.append(
                    f"- **{item['result']} {item['name']}** — {item.get('reason', 'no reason recorded')}"
                )
        contact = [item for item in fusions if "Contact Fusion" in item.get("fusionTypes", [])]
        if contact:
            lines.append("")
            lines.append(
                "Contact Fusion recipes (data-complete, runtime primitive missing): "
                + ", ".join(f"{item['result']} {item['name']}" for item in contact)
                + "."
            )
        unavailable = [
            item
            for item in resolved
            if not item.get("engineReady") and "Contact Fusion" not in item.get("fusionTypes", [])
        ]
        if unavailable:
            lines.append("")
            lines.append(
                "Other resolved but not-yet-engine-ready recipes: "
                + ", ".join(f"{item['result']} {item['name']}" for item in unavailable)
                + "."
            )
    lines.append("")

    lines.append("## Ritual coverage")
    lines.append("")
    try:
        rituals = data.load_json(data.RITUALS_PATH)
    except Exception:
        rituals = []
    if isinstance(rituals, list):
        resolved = [item for item in rituals if item.get("status") == "resolved"]
        lines.append(
            f"- Ritual Monsters: **{len(rituals)}**; resolved procedures: **{len(resolved)}**; "
            f"unresolved: **{len(rituals) - len(resolved)}**."
        )
        confidence_counts = {
            key: sum(1 for item in rituals if item.get("confidence") == key)
            for key in ("high", "medium", "low", "unresolved")
        }
        lines.append(
            "- Confidence: "
            + ", ".join(f"`{key}`={value}" for key, value in confidence_counts.items())
        )
        for item in rituals:
            if item.get("confidence") == "medium":
                note = "; ".join(item.get("notes", []))
                lines.append(f"- **{item['monster']} {item['name']}** — {note}")
    lines.append("")

    lines.append("## Runtime and content blockers")
    lines.append("")
    pending_count = summary["by_status"].get("pending", 0)
    lines.append(
        f"1. **{pending_count} pending effect cards** remain (410 Effect Monsters, 280 Spells, 160 Traps, plus effect-bearing Fusions/Rituals). They are honest `pending` rows, not silent omissions."
    )
    tier2_count = summary["by_tier"].get("2", 0)
    tier2_entries = [entry for entry in entries if entry["tier"] == 2]
    tier2_pending = sum(1 for entry in tier2_entries if entry["status"] == "pending")
    lines.append(
        f"2. **Tier 2 contains {tier2_count} cards** because A06/A07 usage datasets (Shop/packs.json, Opponents, Puzzles, Decks, Exams) now reference most of the pool. "
        f"{tier2_count - tier2_pending} are covered and **{tier2_pending} are pending**. "
        "`audit.py` treats Tier 2 as informational in the baseline stage and as a hard gate with `--release`."
    )
    lines.append(
        "3. **Fusion 1156 UFOroid Fighter** is unresolved: its text mixes one named material with a generic `1 Warrior-Type monster` slot, which the current recipe model cannot express."
    )
    lines.append(
        "4. **Contact Fusion** (745, 747, 774, 775) and **Power Bond / Fusion Gate** are data-valid but not resolved by the current engine. A04 needs the primitives listed in `RUNTIME_INTERFACE.md`."
    )
    lines.append(
        "5. **Ritual procedures** are complete as data (22/22), but the engine currently resolves only Legendary Flame Lord. A04 must load `rituals.json` and support generic Ritual Summons."
    )
    lines.append(
        "6. Tier 0 is green only because the C++ name handlers still exist. The 109 `engine_cpp` rows are the regression contract for A04's refactor."
    )
    lines.append("")

    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Build the report in memory without writing it.",
    )
    args = parser.parse_args(argv)
    report = build_report()
    if not args.check:
        output = data.ROOT / "Docs" / "Effects" / "COVERAGE.md"
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(report, encoding="utf-8", newline="\n")
        print(f"Wrote {output.relative_to(data.ROOT)}")
    else:
        print(report)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
